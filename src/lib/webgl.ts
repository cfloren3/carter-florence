export function webglAvailable() {
  if (typeof window === "undefined") return false;
  try {
    const c = document.createElement("canvas");
    return Boolean(c.getContext("webgl2") || c.getContext("webgl"));
  } catch {
    return false;
  }
}

/** Shared, mutable state written by GSAP and read inside render loops. */
export const glState = {
  /** Smoothed pointer in normalised device coords (-1..1). */
  pointer: { x: 0, y: 0, tx: 0, ty: 0 },
};

if (typeof window !== "undefined") {
  window.addEventListener(
    "pointermove",
    (e) => {
      glState.pointer.tx = (e.clientX / window.innerWidth) * 2 - 1;
      glState.pointer.ty = -((e.clientY / window.innerHeight) * 2 - 1);
    },
    { passive: true }
  );
}

/** Small seeded PRNG (mulberry32) — deterministic, so particle layouts are stable and render stays pure. */
export function prng(seed = 1) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
